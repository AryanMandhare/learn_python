# Operators = Operators perform calculations and comparisons.


# Operator	   Meaning	     Example

#   +	       Addition	      10 + 5

#   -	    Subtraction	      10 - 5

#   *	 Multiplication	      10 * 5

#   /	      Division	      10 / 5

#  //	Floor division	      10 // 3

#  %	     Remainder	      10 % 3

#  **	       Power	      2 ** 3


# Arithmetic operators

a = 10

b = 5

print("Addition:", a + b)  # Addition

print("Subtraction:", a - b)  # Subtraction

print("Multiplication:", a * b)  # Multiplication

print("Division:", a / b)  # Division

print("Floor Division:", a // b)  # Floor division

print("Remainder:", a % b)  # Remainder

print("Power:", a ** b)  # Power


# Comparison operators 



# Operator	  Meaning	                             Example 	      Result

#   ==	 Returns True if both sides are equal	     a == b	           False

#   !=	Returns True if sides are different	         a != b	            True

#   >	    Returns True if left side is larger	     a > b	            False

#   <		Returns True if left side is smaller	 a < b	            True

#   >=    Returns True if left side is larger or     a >= 10	        True
#               exactly equal	

#   <= 	Returns True if left side is smaller or      b <= 20	            True
#               exactly equal	


s = 20
u = 10

print("Equal:", s == u)  # Equal
print("Not Equal:", s != u)  # Not Equal
print("Greater Than:", s > u)  # Greater Than
print("Less Than:", s < u)  # Less Than
print("Greater Than or Equal:", s >= u)  # Greater Than or Equal
print("Less Than or Equal:", s <= u)  # Less Than or Equal